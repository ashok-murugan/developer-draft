# ---------------------------------------------------------------------------
# Merge helpers
# ---------------------------------------------------------------------------

def _merge_vscode_mcp(existing_path: Path, new_server: dict) -> str:
    """Add/replace the task-offloader entry in an existing .vscode/mcp.json."""
    try:
        data = json.loads(existing_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        data = {}
    servers = data.setdefault("servers", {})
    servers["task-offloader"] = new_server
    return json.dumps(data, indent=2) + "\n"


# ---------------------------------------------------------------------------
# Core write helper
# ---------------------------------------------------------------------------

def _write(path: Path, content: str, dry_run: bool, force: bool,
           merge_fn=None) -> InitResult:
    """Write content to path, respecting dry_run and force.

    merge_fn(existing_path) -> str  used for mcp.json merge.
    """
    exists = path.exists()

    if dry_run:
        if not exists:
            return InitResult(path, "would-create")
        if merge_fn:
            return InitResult(path, "would-merge", "existing servers preserved")
        return InitResult(path, "would-skip" if not force else "would-create",
                          "existing" if not force else "would overwrite (--force)")

    path.parent.mkdir(parents=True, exist_ok=True)

    if exists and merge_fn:
        merged = merge_fn(path)
        path.write_text(merged, encoding="utf-8")
        return InitResult(path, "merged", "existing servers preserved")

    if exists and not force:
        return InitResult(path, "skipped", "use --force to overwrite")

    path.write_text(content, encoding="utf-8")
    return InitResult(path, "created")


