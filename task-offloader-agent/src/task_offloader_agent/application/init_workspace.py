def init_workspace(
    workspace: Path,
    model: str,
    venv_bin: Path,
    clients: list[int],      # numbers from CLIENTS menu, e.g. [1, 3]; empty = none
    force: bool = False,
    dry_run: bool = False,
) -> list[InitResult]:
    """Create .task-offloader/ and wire requested AI clients.

    Never overwrites profile.toml even with force=True.
    Returns one InitResult per file attempted.
    """
    results: list[InitResult] = []
    name = workspace.name
    has_logs = (workspace / "logs").is_dir()

    cfg_dir = workspace / ".task-offloader"

    # --- profile.toml (never overwritten) ---
    profile_path = cfg_dir / "profile.toml"
    if profile_path.exists():
        results.append(InitResult(profile_path, "skipped",
                                  "profile is user-owned; edit manually"))
    else:
        content = _render_profile(name, model, has_logs)
        results.append(_write(profile_path, content, dry_run, force=False))

    # --- .gitignore ---
    gi_path = cfg_dir / ".gitignore"
    results.append(_write(gi_path, _GITIGNORE, dry_run, force))

    # --- resolve which file IDs to write ---
    if 5 in clients:
        file_ids = ALL_CLIENT_FILES
    else:
        file_ids: list[str] = []
        for c in CLIENTS:
            if c["n"] in clients:
                file_ids.extend(c["files"])

    if not file_ids:
        return results

    # VS Code mcp.json — always merge
    if "vscode_mcp" in file_ids:
        target = workspace / ".vscode" / "mcp.json"
        server_entry = {
            "type": "stdio",
            "command": venv_bin_str(venv_bin, workspace),
            "args": [
                "--workspace", "${workspaceFolder}",
                "--profile", "${workspaceFolder}/.task-offloader/profile.toml",
                "mcp",
            ],
        }
        content = _render_vscode_mcp(venv_bin)
        results.append(_write(target, content, dry_run, force,
                               merge_fn=lambda p: _merge_vscode_mcp(p, server_entry)))

    if "copilot_instructions" in file_ids:
        target = workspace / ".github" / "copilot-instructions.md"
        results.append(_write(target, _copilot_instructions_content(), dry_run, force))

    if "claude_md" in file_ids:
        target = workspace / "CLAUDE.md"
        results.append(_write(target, _claude_md_content(), dry_run, force))

    if "cursor_mcp" in file_ids:
        target = workspace / ".cursor" / "mcp.json"
        results.append(_write(target, _render_cursor_mcp(venv_bin, workspace), dry_run, force))

    if "cursor_rules" in file_ids:
        target = workspace / ".cursor" / "rules" / "task-offloader.mdc"
        results.append(_write(target, _cursor_rules_content(), dry_run, force))

    if "agy_rules" in file_ids:
        target = workspace / "rules" / "task-offloader.md"
        results.append(_write(target, _agy_rules_content(), dry_run, force))

    if "agy_skill" in file_ids:
        target = workspace / "skills" / "task-offloader" / "SKILL.md"
        results.append(_write(target, _agy_skill_content(), dry_run, force))

    return results