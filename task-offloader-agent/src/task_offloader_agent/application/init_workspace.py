def find_venv_bin(workspace: Path) -> Path | None:
    """Find the task-offloader binary relative to the running Python executable."""
    exe = Path(sys.executable)
    bin_dir = exe.parent  # Scripts/ on Windows, bin/ on POSIX
    for name in ("task-offloader", "task-offloader.exe"):
        candidate = bin_dir / name
        if candidate.exists():
            return candidate
    return None


def venv_bin_str(bin_path: Path, workspace: Path) -> str:
    """Return an absolute POSIX-style string for use inside JSON config files."""
    return bin_path.as_posix()


